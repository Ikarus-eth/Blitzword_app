// Builds assets/adventures/pip-grows/campaign.js from the reviewed story, questions and glossary.
// Run: node docs/adventures/growing-up/build-campaign.js
const fs = require('fs');
const path = require('path');
const story = require('./story-source.js');
const glossary = require('./glossary-source.js');
const OUT = path.join(__dirname, '../../../assets/adventures/pip-grows/campaign.js');
const dir = 'assets/adventures/pip-grows/';
// Part 2 and most of part 3 are memories, so they reuse pictures from the earlier adventures.
const art = {
  'grow-egg': [dir + 'grow-egg-1.webp', dir + 'grow-egg-2.webp', dir + 'grow-egg-3.webp', dir + 'grow-egg-4.webp'],
  'grow-little': ['assets/adventures/mist-lamps.webp', 'assets/adventures/kind-shark-departure.webp', 'assets/adventures/river-heart.webp', 'assets/adventures/first-spark.webp'],
  'grow-big': [dir + 'grow-big-1.webp', 'assets/adventures/thunder-mountain/tm-storm-2.webp', 'assets/adventures/thunder-mountain/tm-home-3.webp', 'assets/adventures/moon-key/mk-river-3.webp'],
  'grow-ride': [dir + 'grow-ride-1.webp', dir + 'grow-ride-2.webp', dir + 'grow-ride-3.webp', dir + 'grow-ride-4.webp'],
};
const meta = {
  'grow-egg': { name: 'The Little Red Egg', place: 'By the Fire', goal: 'Remember where Pip came from.', item: 'A memory: the red egg', symbol: 'seed',
    intro: 'Pip is glowing! Sit by the fire and read how it all began.', ending: 'You read part 1! Pip came out of a little red egg.' },
  'grow-little': { name: 'Little Pip', place: 'The Forest and the River', goal: 'Remember little Pip.', item: 'A memory: the river bells', symbol: 'bell',
    intro: 'Pip was very small once. Read about little Pip.', ending: 'You read part 2! Little Pip was small, but he was brave.' },
  'grow-big': { name: 'Big Pip', place: 'Thunder Mountain', goal: 'Remember how Pip got big.', item: 'A memory: Grandma’s cake', symbol: 'star',
    intro: 'Then one day, Pip was big! Read part 3.', ending: 'You read part 3! Pip is strong because he is kind.' },
  'grow-ride': { name: 'Hop On!', place: 'Artus’s House', goal: 'Help Pip grow.', item: 'A saddle for Pip', symbol: 'sun', finale: true,
    intro: 'The light on Pip is getting brighter. Read the last part. Then Pip can grow!', ending: 'Pip grew! Now Artus can ride on Pip’s back.' },
};
const count = st => st.pages.flat().join(' ').split(/\s+/).filter(w => /[A-Za-z]/.test(w)).length;
const missions = story.parts.map((p, i) => {
  const m = meta[p.id];
  if (!m || art[p.id].length !== p.pages.length) throw new Error('Meta or art missing for ' + p.id);
  const st = { id: 'end', title: p.title, targets: [], pages: p.pages, art: art[p.id],
    questions: p.questions.map(([prompt, page, ...opts], j) => ({ id: p.id + '-q' + (j + 1), prompt, options: opts.map((label, k) => ({ id: String(k), label })), answer: '0', page })) };
  for (const q of st.questions) if (q.page < 1 || q.page > st.pages.length) throw new Error('Bad page for ' + q.id);
  st.words = count(st);
  return { id: p.id, campaign: 'pip-grows', storyOnly: true, name: m.name, place: m.place, families: [], goal: m.goal, item: m.item, symbol: m.symbol,
    intro: m.intro, ending: m.ending, requires: i ? [story.parts[i - 1].id] : [], ...(m.finale ? { finale: true } : {}),
    targets: [], riddles: [], health: [], encounters: [], story: st,
    art: art[p.id][0], artAlt: 'Pip Grows Up, part ' + (i + 1) + ': ' + m.name + '.', endingArt: art[p.id].at(-1), endingArtAlt: 'The end of part ' + (i + 1) + '.',
    scenes: art[p.id].map((a, k) => ({ art: a, alt: 'Story picture ' + (k + 1) + ' for ' + m.name + '.' })) };
});
const campaign = { id: 'pip-grows', name: 'Pip Grows Up', shortName: 'Pip grows', scene: dir + 'grow-cover.webp', growth: true, story: true,
  coverAlt: 'Artus rides on grown-up Pip across a sunny meadow.',
  intro: 'Pip is glowing! Read the story of how Pip and Artus grew up together. When you finish, Pip will grow.',
  ending: 'Pip grew! Now Artus can ride on Pip’s back.', prize: 'Rider of Pip', missions: missions.map(m => m.id) };
const out = `(function(root,factory){const data=factory();if(typeof module==='object'&&module.exports)module.exports=data;else root.BlitzGrowCampaign=data;})(typeof globalThis!=='undefined'?globalThis:this,function(){
  'use strict';
  // Pip Grows Up (12 November 2026). Generated by docs/adventures/growing-up/build-campaign.js from the reviewed story.
  // A story-only chapter: it opens at 44,000 XP, quests pause until it is read, and its last right answer makes Pip grow.
  const glossary=${JSON.stringify(glossary)};
  const missions=${JSON.stringify(missions, null, 1)};
  const campaign=${JSON.stringify(campaign)};
  return {campaign,missions,glossary};
});
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log('wrote', OUT, missions.map(m => m.id + ':' + m.story.words).join(' '), 'total', missions.reduce((n, m) => n + m.story.words, 0));
