// Builds assets/adventures/moon-key/campaign.js from the reviewed story, questions and glossary drafts.
const fs = require('fs');
const story = require('./story-source.js');
const Qs = require('./questions-source.js');
const glossary = require('./glossary-source.js');
const OUT = require('path').join(__dirname, '../../../assets/adventures/moon-key/campaign.js');

const meta = {
  'mk-owl': { name: 'The Owl at the Window', place: 'Artus’s Window', families: ['moon-hare-knight', 'velvet-shrew'], goal: 'Find out where the moon is.', item: 'The owls’ white bell', symbol: 'bell',
    intro: 'There is no moon in the sky! Learn the new words, then read part 1 of the story.', ending: 'You read part 1! Now Artus, Pip and Jet go down to the river.' },
  'mk-river': { name: 'The Beaver’s Boat', place: 'The Big Waterfall', families: ['dam-beaver', 'brook-turtle'], goal: 'Get past the waterfall.', item: 'A little wood boat', symbol: 'leaf',
    intro: 'There is a big waterfall on the river. Learn the river words, then read part 2.', ending: 'You read part 2! The little boat goes down the river.' },
  'mk-fog': { name: 'The Fox in the Fog', place: 'The Foggy River', families: ['cloak-raccoon', 'amber-newt'], goal: 'Find out where the black bird went.', item: 'The way to the island', symbol: 'map',
    intro: 'There is fog on the river, and the friends can’t see. Learn the new words, then read part 3.', ending: 'You read part 3! Now they know where the black bird is.' },
  'mk-town': { name: 'Sam’s Ship', place: 'The Town by the Ocean', families: ['cattail-heron', 'marsh-crane'], goal: 'Find a ship to the island.', item: 'A place on Sam’s ship', symbol: 'rope',
    intro: 'The friends come to a town by the ocean. Learn the town words, then read part 4.', ending: 'You read part 4! The old ship goes out on the ocean.' },
  'mk-storm': { name: 'The Storm', place: 'Out on the Ocean', families: ['shell-lobster', 'glacier-seal'], goal: 'Get to the island.', item: 'A shark friend', symbol: 'wing',
    intro: 'A big storm comes over the ocean. Learn the storm words, then read part 5.', ending: 'You read part 5! Jet is safe, and they can see the island.' },
  'mk-castle': { name: 'The Little Ghost', place: 'The Old Castle', families: ['slate-pangolin', 'cinder-porcupine'], goal: 'Go into the old castle.', item: 'A new friend called May', symbol: 'gem',
    intro: 'There is an old castle on the island. Learn the castle words, then read part 6.', ending: 'You read part 6! May knows where the black bird is.' },
  'mk-nest': { name: 'The Nest', place: 'The Top of the Castle', families: ['ink-raven', 'honey-wasp'], goal: 'Find the Moon Key.', item: 'The Moon Key', symbol: 'star',
    intro: 'The black bird has a nest at the top of the castle. Learn the new words, then read part 7.', ending: 'You read part 7! The Moon Key is in the nest.' },
  'mk-moon': { name: 'The Moon Comes Back', place: 'The Night Sky', families: ['bell-tortoise', 'petal-chameleon'], goal: 'Bring back the moon.', item: 'The moon in the sky', symbol: 'moon', finale: true,
    intro: 'It is time to bring back the moon! Learn the last words, then read the end of the story.', ending: 'You read the whole story by yourself! The moon is back in the sky.' },
};

const questions = (id, which) => Qs[id][which].map(([prompt, page, ...opts], i) => ({
  id: id + (which === 'mid' ? '-m' : '-q') + (i + 1), prompt,
  options: opts.map((label, j) => ({ id: String(j), label })), answer: '0', page,
}));

const missions = story.quests.map((q, i) => {
  const m = meta[q.id];
  if (!m) throw new Error('No meta for ' + q.id);
  return {
    id: q.id, name: m.name, place: m.place, families: m.families, goal: m.goal, item: m.item, symbol: m.symbol,
    intro: m.intro, ending: m.ending, requires: i ? [story.quests[i - 1].id] : [], ...(m.finale ? { finale: true } : {}),
    area: 'moon-ch' + (i + 1), health: [10, 11, 12, 14],
    mid: { title: q.mid.title, pages: q.mid.pages, questions: questions(q.id, 'mid') },
    story: { title: q.end.title, targets: q.targets, pages: q.end.pages, questions: questions(q.id, 'end') },
    riddles: [],
  };
});

const src = `(function(root,factory){const data=factory();if(typeof module==='object'&&module.exports)module.exports=data;else root.BlitzMoonCampaign=data;})(typeof globalThis!=='undefined'?globalThis:this,function(){
  'use strict';
  // Story campaign 5, Pip and the Moon Key (8 November 2026). Generated by docs/adventures/moon-key/build-campaign.js
  // from the reviewed story text. Each quest runs fight, fight, mid story, fight, fight, end story, like Thunder Mountain,
  // but the stories are about three times longer. Every word is tappable; meanings for words that the Thunder Mountain
  // glossary does not already have are below: [simple meaning, syllables (a|b), tricky letters].
  const glossary=${JSON.stringify(glossary, null, 0).replace(/\],"/g, '],\n  "')};
  const missions=${JSON.stringify(missions, null, 1)};
  const dir='assets/adventures/moon-key/';
  const count=story=>story.pages.flat().join(' ').split(/\\s+/).filter(w=>/[A-Za-z]/.test(w)).length;
  for(const m of missions){m.campaign='moon-key';m.targets=m.story.targets;
    m.mid={...m.mid,id:'mid',targets:m.targets,art:m.mid.pages.map((p,i)=>dir+m.id+'-a'+(i+1)+'.webp')};m.mid.words=count(m.mid);
    m.story.id='end';
    m.scenes=m.story.pages.map((p,i)=>({art:dir+m.id+'-'+(i+1)+'.webp',alt:'Story picture '+(i+1)+' for '+m.name+'.'}));
    m.art=m.mid.art[0];m.artAlt='Artus, Pip and Jet: '+m.place+'.';m.endingArt=m.scenes.at(-1).art;m.endingArtAlt='The end of '+m.name+'.';
    m.story.words=count(m.story);m.story.art=m.scenes.map(x=>x.art);m.stories=[m.mid,m.story];}
  const campaign={id:'moon-key',name:'Pip and the Moon Key',shortName:'Moon Key',scene:dir+'cover.webp',coverAlt:'Artus, Pip and Jet look up at the night sky with no moon.',story:true,
    intro:'There is no moon in the sky! In each quest, win two fights to learn new words, then read a long story by yourself. Do it twice!',
    ending:'You read the whole story by yourself! The moon is back in the sky.',prize:'Reader of the Moon Key',missions:missions.map(m=>m.id)};
  return {campaign,missions,glossary};
});
`;
fs.mkdirSync(require('path').dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, src);
const data = require(OUT);
console.log('missions', data.missions.length, 'words', data.missions.reduce((n, m) => n + m.mid.words + m.story.words, 0));
